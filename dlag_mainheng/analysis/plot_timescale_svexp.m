function filename = findFirstFileLocal( ...
    folderPath, ...
    pattern)

    files = dir(fullfile(folderPath, pattern));

    if isempty(files)
        error( ...
            'No %s file found in %s', ...
            pattern, ...
            folderPath);
    end

    % Explicit alphabetical sorting gives deterministic behavior and is
    % consistent with taking the first matching file.
    [~, fileOrder] = sort({files.name});
    files = files(fileOrder);

    if numel(files) > 1
        warning( ...
            ['Multiple files matched "%s" in %s. ', ...
             'Using the first file: %s'], ...
            pattern, ...
            folderPath, ...
            files(1).name);
    end

    filename = fullfile( ...
        folderPath, ...
        files(1).name);
end

function saveFigureLocal( ...
    figHandle, ...
    folderPath, ...
    baseName, ...
    export_resolution)

    if isempty(figHandle) || ~isgraphics(figHandle)
        return;
    end

    if ~exist(folderPath, 'dir')
        mkdir(folderPath);
    end

    figFile = fullfile( ...
        folderPath, ...
        [baseName, '.fig']);

    pngFile = fullfile( ...
        folderPath, ...
        [baseName, '.png']);

    savefig(figHandle, figFile);

    try
        exportgraphics( ...
            figHandle, ...
            pngFile, ...
            'Resolution', export_resolution);
    catch
        saveas(figHandle, pngFile);
    end

    fprintf('Saved figure to %s\n', figFile);
    fprintf('Saved image to %s\n', pngFile);
end

function validateUserParametersLocal( ...
    rGroups, ...
    marker_area_scale, ...
    minimum_marker_area, ...
    maximum_marker_area, ...
    within_x_center, ...
    within_x_spread, ...
    delay_xlim, ...
    timescale_ylim)

    rGroups = reshape(double(rGroups), 1, []);

    if numel(rGroups) ~= 2 || ...
            any(~isfinite(rGroups)) || ...
            any(rGroups < 1) || ...
            any(rGroups ~= round(rGroups)) || ...
            rGroups(1) == rGroups(2)

        error( ...
            'rGroups must contain two distinct positive integer group indexes.');
    end

    if ~isscalar(marker_area_scale) || ...
            ~isfinite(marker_area_scale) || ...
            marker_area_scale <= 0

        error('marker_area_scale must be a positive finite scalar.');
    end

    if ~isscalar(minimum_marker_area) || ...
            ~isfinite(minimum_marker_area) || ...
            minimum_marker_area < 0

        error( ...
            'minimum_marker_area must be a nonnegative finite scalar.');
    end

    if ~isscalar(maximum_marker_area) || ...
            isnan(maximum_marker_area) || ...
            maximum_marker_area <= 0

        error( ...
            'maximum_marker_area must be a positive scalar or Inf.');
    end

    if maximum_marker_area < minimum_marker_area
        error( ...
            ['maximum_marker_area cannot be smaller than ', ...
             'minimum_marker_area.']);
    end

    if ~isscalar(within_x_center) || ...
            ~isfinite(within_x_center)

        error('within_x_center must be a finite scalar.');
    end

    if ~isscalar(within_x_spread) || ...
            ~isfinite(within_x_spread) || ...
            within_x_spread < 0

        error('within_x_spread must be a nonnegative finite scalar.');
    end

    if ~isempty(delay_xlim)
        delay_xlim = reshape(double(delay_xlim), 1, []);

        if numel(delay_xlim) ~= 2 || ...
                any(~isfinite(delay_xlim)) || ...
                delay_xlim(2) <= delay_xlim(1)

            error( ...
                'delay_xlim must be [] or a finite increasing two-element vector.');
        end
    end

    if ~isempty(timescale_ylim)
        timescale_ylim = reshape(double(timescale_ylim), 1, []);

        if numel(timescale_ylim) ~= 2 || ...
                any(~isfinite(timescale_ylim)) || ...
                timescale_ylim(2) <= timescale_ylim(1)

            error( ...
                ['timescale_ylim must be [] or a finite increasing ', ...
                 'two-element vector.']);
        end
    end
end