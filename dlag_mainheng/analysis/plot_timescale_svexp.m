function plotAcrossPanelLocal( ...
    ax, ...
    delay, ...
    tau, ...
    markerArea, ...
    isAmbiguous, ...
    groupIdx, ...
    rGroups, ...
    delayLim, ...
    timescaleLim, ...
    ff_fb_color, ...
    ambiguous_color, ...
    marker_edge_line_width, ...
    zero_delay_line_color, ...
    zero_delay_line_width, ...
    font_size, ...
    axes_line_width)

    hold(ax, 'on');

    xlim(ax, delayLim);
    ylim(ax, timescaleLim);

    % Zero-delay reference line
    plot( ...
        ax, ...
        [0 0], ...
        timescaleLim, ...
        '--', ...
        'Color', zero_delay_line_color, ...
        'LineWidth', zero_delay_line_width, ...
        'HandleVisibility', 'off');

    validIdx = find( ...
        isfinite(delay) & ...
        isfinite(tau) & ...
        isfinite(markerArea) & ...
        markerArea > 0);

    % Draw large circles first and small circles afterward so that a small
    % circle is less likely to be completely hidden.
    if ~isempty(validIdx)
        [~, areaOrder] = sort( ...
            markerArea(validIdx), ...
            'descend');

        drawIdx = validIdx(areaOrder);

        for idx_i = 1:numel(drawIdx)

            latentIdx = drawIdx(idx_i);

            if isAmbiguous(latentIdx)
                thisColor = ambiguous_color;
            else
                thisColor = ff_fb_color;
            end

            scatter( ...
                ax, ...
                delay(latentIdx), ...
                tau(latentIdx), ...
                markerArea(latentIdx), ...
                'o', ...
                'filled', ...
                'MarkerFaceColor', thisColor, ...
                'MarkerEdgeColor', thisColor, ...
                'LineWidth', marker_edge_line_width, ...
                'HandleVisibility', 'off');
        end
    end

    xlabel( ...
        ax, ...
        sprintf( ...
            'Delay from area %d to area %d', ...
            rGroups(1), ...
            rGroups(2)));

    ylabel(ax, 'GP timescale');

    title( ...
        ax, ...
        sprintf( ...
            'Across-area latents, group %d', ...
            groupIdx), ...
        'FontWeight', 'normal');

    formatAxesLocal( ...
        ax, ...
        font_size, ...
        axes_line_width);
end

