function [f, xi] = estimateDensityLocal(vals)

    vals = vals(:);
    vals = vals(isfinite(vals));

    if isempty(vals) || ...
            numel(vals) < 2 || ...
            max(vals) == min(vals)

        f = [];
        xi = [];
        return;
    end

    if exist('ksdensity', 'file') == 2

        try
            [f, xi] = ksdensity( ...
                vals, ...
                'NumPoints', 100);

            return;

        catch
            % Fall through to histogram fallback.
        end
    end

    numBins = min( ...
        20, ...
        max(5, round(sqrt(numel(vals)))));

    try
        [counts, edges] = histcounts( ...
            vals, ...
            numBins, ...
            'Normalization', 'pdf');

    catch
        [counts, edges] = histcounts(vals, numBins);

        binWidth = mean(diff(edges));

        counts = counts ./ ...
            (sum(counts) * binWidth);
    end

    xi = edges(1:end-1) + diff(edges) / 2;
    f = counts;

    valid = isfinite(f) & isfinite(xi);

    f = f(valid);
    xi = xi(valid);
end

function xJitter = densityAwareJitterLocal( ...
    vals, ...
    xPos, ...
    maxJitterWidth)

    vals = vals(:);

    if isempty(vals)
        xJitter = [];
        return;
    end

    if numel(vals) < 2 || max(vals) == min(vals)

        xJitter = xPos + zeros(size(vals));
        return;
    end

    [f, xi] = estimateDensityLocal(vals);

    if isempty(f) || isempty(xi) || max(f) <= 0

        xJitter = xPos + ...
            (rand(size(vals)) - 0.5) * ...
            2 * maxJitterWidth;

        return;
    end

    f = f(:);
    xi = xi(:);

    densityAtVals = interp1( ...
        xi, ...
        f, ...
        vals, ...
        'linear', ...
        'extrap');

    densityAtVals(~isfinite(densityAtVals)) = 0;
    densityAtVals(densityAtVals < 0) = 0;

    if max(densityAtVals) > 0

        densityAtVals = ...
            densityAtVals ./ max(densityAtVals);

    else

        densityAtVals = ones(size(vals));
    end

    densityFloor = 0.08;

    densityAtVals = ...
        densityFloor + ...
        (1 - densityFloor) .* densityAtVals;

    localWidth = ...
        maxJitterWidth .* densityAtVals;

    xJitter = ...
        xPos + ...
        (rand(size(vals)) - 0.5) .* ...
        2 .* localWidth;
end

function limVals = paddedLimitsLocal( ...
    vals, ...
    defaultLim)

    vals = vals(:);
    vals = vals(isfinite(vals));

    if isempty(vals)
        limVals = defaultLim;
        return;
    end

    minVal = min(vals);
    maxVal = max(vals);

    if minVal == maxVal

        padVal = max( ...
            0.1, ...
            abs(minVal) * 0.1);

    else

        padVal = ...
            0.05 * (maxVal - minVal);
    end

    limVals = [
        minVal - padVal, ...
        maxVal + padVal
    ];

    if limVals(1) == limVals(2)

        limVals = ...
            limVals + [-0.1, 0.1];
    end
end

